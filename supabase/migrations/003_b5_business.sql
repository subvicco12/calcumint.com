create policy "organizations_member_select" on public.organizations for select using (public.is_org_member(id));
create policy "organizations_admin_update" on public.organizations for update using (public.has_org_role(id, array['owner','admin'])) with check (public.has_org_role(id, array['owner','admin']));

create policy "members_org_select" on public.organization_members for select using (public.is_org_member(organization_id));
create policy "members_admin_update" on public.organization_members for update using (public.has_org_role(organization_id, array['owner','admin'])) with check (role <> 'owner' or public.org_role(organization_id) = 'owner');
create policy "members_admin_delete" on public.organization_members for delete using (public.has_org_role(organization_id, array['owner','admin']) and role <> 'owner');

create policy "invites_admin_select" on public.organization_invitations for select using (public.has_org_role(organization_id, array['owner','admin']));
create policy "invites_admin_insert" on public.organization_invitations for insert with check (public.has_org_role(organization_id, array['owner','admin']) and invited_by = auth.uid());
create policy "invites_admin_delete" on public.organization_invitations for delete using (public.has_org_role(organization_id, array['owner','admin']));

create policy "projects_member_select" on public.business_projects for select using (public.is_org_member(organization_id));
create policy "projects_manager_insert" on public.business_projects for insert with check (public.has_org_role(organization_id, array['owner','admin','manager']) and created_by = auth.uid());
create policy "projects_manager_update" on public.business_projects for update using (public.has_org_role(organization_id, array['owner','admin','manager']));

create policy "clients_member_select" on public.client_workspaces for select using (public.is_org_member(organization_id));
create policy "clients_manager_insert" on public.client_workspaces for insert with check (public.has_org_role(organization_id, array['owner','admin','manager']) and created_by = auth.uid());
create policy "clients_manager_update" on public.client_workspaces for update using (public.has_org_role(organization_id, array['owner','admin','manager']));

create policy "shared_member_select" on public.shared_calculations for select using (public.is_org_member(organization_id));
create policy "shared_editor_insert" on public.shared_calculations for insert with check (public.has_org_role(organization_id, array['owner','admin','manager','member']) and created_by = auth.uid());
create policy "shared_editor_update" on public.shared_calculations for update using (public.has_org_role(organization_id, array['owner','admin','manager','member']));

create policy "audit_member_select" on public.organization_audit_log for select using (public.is_org_member(organization_id));

