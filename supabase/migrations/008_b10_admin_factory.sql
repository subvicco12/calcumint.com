-- CalcuMint B10: platform administration, review workflow and publishing factory

create table if not exists public.platform_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','admin','reviewer','editor')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.is_platform_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.platform_admins a where a.user_id = auth.uid() and a.active)
$$;

create or replace function public.has_platform_role(allowed text[])
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.platform_admins a where a.user_id = auth.uid() and a.active and a.role = any(allowed))
$$;

create table if not exists public.calculator_catalog_admin (
  id uuid primary key default gen_random_uuid(),
  calculator_key text not null unique,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  title text not null check (char_length(title) between 2 and 160),
  category text not null check (char_length(category) between 2 and 100),
  risk_class text not null default 'standard' check (risk_class in ('standard','financial','health','tax')),
  lifecycle text not null default 'draft' check (lifecycle in ('draft','review','certified','published','archived')),
  version integer not null default 1 check (version > 0),
  reviewer_id uuid references auth.users(id) on delete set null,
  review_notes text,
  source_count integer not null default 0 check (source_count >= 0),
  publish_at timestamptz,
  published_at timestamptz,
  last_reviewed_at timestamptz,
  next_review_due_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.calculator_qa_checks (
  id uuid primary key default gen_random_uuid(),
  calculator_id uuid not null references public.calculator_catalog_admin(id) on delete cascade,
  check_type text not null check (check_type in ('engine-tests','formula-review','sources','methodology','seo-content','accessibility','ymyl-review')),
  status text not null default 'pending' check (status in ('pending','passed','failed','waived')),
  details text,
  checked_by uuid references auth.users(id) on delete set null,
  checked_at timestamptz,
  unique(calculator_id, check_type)
);

create table if not exists public.calculator_review_events (
  id bigint generated by default as identity primary key,
  calculator_id uuid not null references public.calculator_catalog_admin(id) on delete cascade,
  actor_id uuid not null references auth.users(id) on delete restrict,
  event_type text not null,
  from_state text,
  to_state text,
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.calculator_bulk_jobs (
  id uuid primary key default gen_random_uuid(),
  job_type text not null check (job_type in ('inventory-import','qa-refresh','review-reminder','scheduled-publish')),
  status text not null default 'queued' check (status in ('queued','processing','completed','failed')),
  requested_by uuid not null references auth.users(id) on delete restrict,
  payload jsonb not null default '{}'::jsonb,
  result jsonb,
  error_message text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz
);

create table if not exists public.admin_alerts (
  id uuid primary key default gen_random_uuid(),
  calculator_id uuid references public.calculator_catalog_admin(id) on delete cascade,
  severity text not null check (severity in ('info','warning','critical')),
  alert_type text not null,
  message text not null,
  status text not null default 'open' check (status in ('open','acknowledged','resolved')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists calculator_admin_lifecycle_idx on public.calculator_catalog_admin(lifecycle, updated_at desc);
create index if not exists calculator_admin_review_due_idx on public.calculator_catalog_admin(next_review_due_at) where lifecycle = 'published';
create index if not exists qa_checks_calculator_idx on public.calculator_qa_checks(calculator_id, check_type);
create index if not exists review_events_calculator_idx on public.calculator_review_events(calculator_id, created_at desc);
create index if not exists admin_alerts_status_idx on public.admin_alerts(status, severity, created_at desc);

