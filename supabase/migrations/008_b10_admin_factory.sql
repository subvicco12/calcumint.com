-- platform_admins intentionally has no authenticated INSERT/UPDATE/DELETE policy.
-- Bootstrap/role changes must be performed with the service role or controlled operations tooling.

create or replace function public.validate_calculator_publish_gate(p_calculator_id uuid)
returns table(ok boolean, failures text[])
language plpgsql
security definer
set search_path = public
as $$
declare v_calc public.calculator_catalog_admin%rowtype;
declare v_failures text[] := '{}';
declare v_required text[] := array['engine-tests','formula-review','sources','methodology','seo-content','accessibility'];
declare v_check text;
declare v_status text;
begin
  select * into v_calc from public.calculator_catalog_admin where id = p_calculator_id;
  if v_calc.id is null then return query select false, array['Calculator not found']; return; end if;
  if v_calc.source_count < 1 then v_failures := array_append(v_failures, 'At least one reviewed source is required'); end if;
  if v_calc.risk_class in ('financial','health','tax') then
    v_required := array_append(v_required, 'ymyl-review');
    if v_calc.reviewer_id is null then v_failures := array_append(v_failures, 'YMYL reviewer is required'); end if;
  end if;
  foreach v_check in array v_required loop
    select status into v_status from public.calculator_qa_checks where calculator_id = p_calculator_id and check_type = v_check;
    if coalesce(v_status, 'pending') not in ('passed','waived') then
      v_failures := array_append(v_failures, format('%s must pass', v_check));
    end if;
  end loop;
  return query select cardinality(v_failures) = 0, v_failures;
end;
$$;

revoke all on function public.validate_calculator_publish_gate(uuid) from public;
grant execute on function public.validate_calculator_publish_gate(uuid) to authenticated, service_role;

create or replace function public.enforce_calculator_publish_gate()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_ok boolean; declare v_failures text[];
begin
  if new.lifecycle in ('certified','published') and new.lifecycle is distinct from old.lifecycle then
    select ok, failures into v_ok, v_failures from public.validate_calculator_publish_gate(new.id);
    if not v_ok then raise exception 'Publishing gate failed: %', array_to_string(v_failures, '; '); end if;
  end if;
  if new.lifecycle = 'published' and new.published_at is null then new.published_at := now(); end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger calculator_publish_gate_before_update before update on public.calculator_catalog_admin
for each row execute function public.enforce_calculator_publish_gate();
