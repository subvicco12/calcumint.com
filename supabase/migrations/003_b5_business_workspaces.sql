create or replace function public.organization_role_rank(p_role public.organization_role)
returns integer language sql immutable as $$
  select case p_role
    when 'viewer' then 10 when 'member' then 20 when 'manager' then 30 when 'admin' then 40 when 'owner' then 50
  end;
$$;

create or replace function public.has_organization_role(p_organization_id uuid, p_min_role public.organization_role)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.organization_members m
    where m.organization_id = p_organization_id
      and m.user_id = auth.uid()
      and public.organization_role_rank(m.role) >= public.organization_role_rank(p_min_role)
  );
$$;

create or replace function public.create_business_organization(p_name text, p_slug text)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v_id uuid;
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and plan = 'business') then
    raise exception 'Business plan required';
  end if;
  insert into public.organizations(name, slug, created_by)
  values (trim(p_name), lower(trim(p_slug)), auth.uid()) returning id into v_id;
  insert into public.organization_members(organization_id, user_id, role)
  values (v_id, auth.uid(), 'owner');
  insert into public.organization_audit_events(organization_id, actor_user_id, action, target_type, target_id)
  values (v_id, auth.uid(), 'organization.created', 'organization', v_id::text);
  return v_id;
end;
$$;

create or replace function public.accept_business_invitation(p_token_hash text)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v_invite public.organization_invitations%rowtype;
  v_email text;
begin
  select lower(coalesce(auth.jwt()->>'email','')) into v_email;
  select * into v_invite
  from public.organization_invitations
  where token_hash = p_token_hash
    and status = 'pending'
    and expires_at > now()
    and lower(email) = v_email
  for update;
  if v_invite.id is null then raise exception 'Invitation is invalid or expired'; end if;
  insert into public.organization_members(organization_id, user_id, role)
  values (v_invite.organization_id, auth.uid(), v_invite.role)
  on conflict (organization_id, user_id) do update set role = excluded.role;
  update public.organization_invitations
  set status = 'accepted', accepted_at = now()
  where id = v_invite.id;
  insert into public.organization_audit_events(organization_id, actor_user_id, action, target_type, target_id)
  values (v_invite.organization_id, auth.uid(), 'invitation.accepted', 'invitation', v_invite.id::text);
  return v_invite.organization_id;
end;
$$;

